'use strict';

const fs = require('node:fs');
const path = require('node:path');

require('./school-themes.js');

const catalog = globalThis.CMS_SCHOOL_THEME_CATALOG;
const outputPath = path.join(__dirname, 'school-themes.css');
const blocks = Object.entries(catalog.schools).map(([themeId, school]) => `
:root[data-studio-skin="${themeId}"] .cms-studio,
.cms-studio[data-studio-skin="${themeId}"] {
  --studio-accent: ${school.primary};
  --studio-accent-hover: ${school.hover};
  --studio-accent-secondary: ${school.secondary};
}

.cms-studio .skin-option[data-ui-skin="${themeId}"] {
  --skin-accent: ${school.primary};
  --skin-secondary: ${school.secondary};
}`.trim());

const css = `/*
 * Generated by generate-school-theme-css.js from school-themes.js.
 *
 * Do not hand-edit school blocks. Regenerate after changing the catalogue:
 * node tools/local-cms/generate-school-theme-css.js
 */

.cms-studio {
  --studio-accent: #8c1515;
  --studio-accent-hover: #6f1010;
  --studio-accent-secondary: #175e54;
  --skin-accent: var(--studio-accent);
  --skin-secondary: var(--studio-accent-secondary);
}

${blocks.join('\n\n')}
`;

fs.writeFileSync(outputPath, css, 'utf8');
console.log(`Generated ${Object.keys(catalog.schools).length} school theme blocks in ${outputPath}`);
